"""Compare actual checkpoint generations or inspect metrics on labeled fixture data."""
# Compare topic-004/006 checkpoints using the same generation rules as topic 005.
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from llm_workshop.evaluate import score
from llm_workshop.teaching import Session, common_parser, show
import torch

# Explicitly invented metric examples, not measured outputs from trained domain models.
REFERENCES = ['positive', 'negative', 'neutral', 'positive', 'negative', 'neutral']
PREDICTIONS = ['positive', 'neutral', 'neutral', 'positive', 'negative', 'invalid answer']


def metrics(predictions=PREDICTIONS):
    if len(predictions) != len(REFERENCES):
        raise ValueError(f'Enter exactly {len(REFERENCES)} predictions, one per line.')
    rows = [{'prediction': p, 'reference': r, 'task': 'finance'} for p, r in zip(predictions, REFERENCES)]
    return score(rows)


def compare(left, right, prompt='the ', tokens=40):
    if left.vocabulary != right.vocabulary:  # Require matching token IDs and meanings.
        raise ValueError('This controlled comparison requires the same tokenizer vocabulary.')
    results = []
    for session in (left, right):
        with torch.inference_mode():
            ids = session.ids(prompt)  # Encode the same prompt for each model.
            generated = session.model.generate(ids, tokens, temperature=0)[0]  # Greedy decoding keeps the comparison controlled.
        results.append({'model': session.label, 'prompt': prompt, 'decoding': 'greedy',
                        'output': session.decode(generated.tolist())})
    return results


def main():
    parser = common_parser(__doc__)
    parser.add_argument('--left', type=Path)
    parser.add_argument('--right', type=Path)
    args = parser.parse_args()
    if bool(args.left) != bool(args.right):
        parser.error('Provide both --left and --right for a real model comparison.')
    if args.left:
        left, right = Session(), Session()
        left.load(args.left)  # Load the first saved model and tokenizer.
        right.load(args.right)  # Load the second saved model and tokenizer.
        for result in compare(left, right, args.text):
            show('Measured checkpoint output', result, args.step)
    else:
        print('MANUAL FIXTURE: these labels were invented to teach metrics, not generated by models.')
        show('References', REFERENCES, args.step)
        show('Predictions', PREDICTIONS, args.step)
        show('Exact match / macro F1 / invalid labels', metrics(), args.step)
    print('Use fixed prompts, held-out data, matching tokenizer and decoding settings.')


if __name__ == '__main__':
    main()
